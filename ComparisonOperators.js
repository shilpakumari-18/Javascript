//Equal to (==) -only checks for value not type.

console.log(6=="6");


//Strictly Equal to (===)-checks for value and type.

console.log(6 ==="6");

//Not Equal to (!=) - only checks for value not type.

console.log(6!="6");

//Strictly Not Equal to (!==) -checks for value and type.

console.log(6 !=="6");