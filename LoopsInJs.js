//Loops are used to repeat code.

//1.forloop-Used when number of iterations is known. 1. initialization,2. condition,3. increment/decrement

for(let i=0;i<=5;i++)
{
    console.log(i);
}

//2.While Runs while condition is true.
let j=0;
while(j<=5){
    console.log(j);
    j++;
}

//3.Do while- runs at least once, then checks condition.
let k=0;
do{
    console.log(k);
    k++;
}while(k<=5);

