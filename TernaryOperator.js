//Short form of if/else. syntax: condition ? expression1 : expersion2

let age =20;
let result = age>=18 ? "Adult" : "Minor";
console.log(result); //Adult

let marks=85;
let grade = marks>=90 ? "Grade A" : (marks>=70 ? "Grade B" : "Grade C");
console.log(grade); //Grade B

let num=10;
let number =num%2==0 ? "Even" : "Odd";
